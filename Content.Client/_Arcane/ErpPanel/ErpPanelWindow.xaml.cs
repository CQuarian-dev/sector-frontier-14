    private bool InteractionMatchesSearch(PanelInteractionPrototype interaction, string searchText)
    {
        if (string.IsNullOrEmpty(searchText))
            return true;

        if (GetInteractionName(interaction).Contains(searchText, StringComparison.CurrentCultureIgnoreCase))
            return true;

        var category = _prototypeManager.Index<PanelInteractionCategoryPrototype>(interaction.Category.Id);
        return GetCategoryName(category).Contains(searchText, StringComparison.CurrentCultureIgnoreCase);
    }

    private string GetInteractionName(PanelInteractionPrototype interaction)
    {
        if (_interactionNames.TryGetValue(interaction.ID, out var name))
            return name;

        name = Loc.GetString($"erp-panel-interaction-{ToKebabCase(interaction.ID)}-name");
        _interactionNames[interaction.ID] = name;
        return name;
    }

    private string GetCategoryName(PanelInteractionCategoryPrototype category)
    {
        if (_categoryNames.TryGetValue(category.ID, out var name))
            return name;

        name = Loc.GetString($"erp-panel-category-{ToKebabCase(category.ID)}-name");
        _categoryNames[category.ID] = name;
        return name;
    }

