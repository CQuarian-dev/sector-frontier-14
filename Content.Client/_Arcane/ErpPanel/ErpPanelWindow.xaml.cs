    internal static string ToKebabCase(string value) // Lua
    {
        var builder = new System.Text.StringBuilder(value.Length * 2);

        for (var i = 0; i < value.Length; i++)
        {
            var character = value[i];

            if (char.IsUpper(character))
            {
                if (i > 0)
                    builder.Append('-');

                builder.Append(char.ToLowerInvariant(character));
                continue;
            }

            builder.Append(character);
        }

        return builder.ToString();
    }

    private bool CheckRequirements(EntityUid user, EntityUid target, PanelInteractionPrototype interaction)
    {
        if (interaction.IsErotic && !CanUseErp(user, target)) // Lua
            return false;

        if (!IsInRange(user, target, interaction.Range)) // Lua
            return false;

        if (interaction.UserRequirements != null)
        {
            foreach (var requirement in interaction.UserRequirements)
            {
                if (!requirement.IsAvailable(user, _entManager))
                    return false;
            }
        }

        if (interaction.TargetRequirements != null)
        {
            foreach (var requirement in interaction.TargetRequirements)
            {
                if (!requirement.IsAvailable(target, _entManager))
                    return false;
            }
        }

        return true;
    }

    // Lua start: same check as the server, one raycast per distinct range
    private bool IsInRange(EntityUid user, EntityUid target, float range)
    {
        if (_rangeCache.TryGetValue(range, out var inRange))
            return inRange;

        inRange = _interaction.InRangeAndAccessible(user, target, range);
        _rangeCache[range] = inRange;
        return inRange;
    }
    // Lua end

    private bool CanUseErp(EntityUid user, EntityUid target)
    {
        if (!_entManager.TryGetComponent<ErpStatusComponent>(user, out var userStatus) ||
            userStatus.Status == EnumERPStatus.NO)
            return false;

        if (user == target)
            return true;

        return _entManager.TryGetComponent<ErpStatusComponent>(target, out var targetStatus)
               && targetStatus.Status != EnumERPStatus.NO;
    }
